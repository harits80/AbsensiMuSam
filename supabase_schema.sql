do $$
declare
  t text;
begin
  foreach t in array array[
    'system_roles',
    'organizations',
    'user_profiles',
    'departments',
    'positions',
    'organization_members',
    'device_types',
    'attendance_devices',
    'shifts',
    'work_schedules',
    'work_schedule_details',
    'member_schedules',
    'shift_assignments',
    'attendance_records',
    'attendance_logs',
    'biometric_data',
    'rfid_cards'
  ]
  loop
    execute format('drop policy if exists "authenticated all access" on public.%I', t);
    execute format(
      'create policy "authenticated all access" on public.%I for all to authenticated using (true) with check (true)',
      t
    );
  end loop;
end $$;

