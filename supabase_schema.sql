do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where conname = 'departments_head_member_id_fkey'
      and conrelid = 'public.departments'::regclass
  ) then
    alter table public.departments
      add constraint departments_head_member_id_fkey
      foreign key (head_member_id) references public.organization_members(id) on delete set null;
  end if;
end $$;

